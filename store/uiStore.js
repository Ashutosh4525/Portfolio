export const useUIStore = create((set) => ({
  sidebarOpen: true,
  terminalOpen: false,
  layoutMode: 'editor',
  contentVariant: 'classic',
  themeId: 'darkPlus',
  setSidebarOpen: (value) => set({ sidebarOpen: value }),
  toggleSidebar: () => set((state) => ({ sidebarOpen: !state.sidebarOpen })),
  toggleTerminal: () => set((state) => ({ terminalOpen: !state.terminalOpen })),
  setTerminalOpen: (value) => set({ terminalOpen: value }),
  setLayoutMode: (layoutMode) => set({ layoutMode }),
  setContentVariant: (contentVariant) => set({ contentVariant }),
  toggleContentVariant: () =>
    set((state) => {
      const currentIndex = contentVariants.indexOf(state.contentVariant);
      return { contentVariant: contentVariants[(currentIndex + 1) % contentVariants.length] };
    }),
  setThemeId: (themeId) => set({ themeId }),
  cycleLayoutMode: () =>
    set((state) => {
      const currentIndex = layoutModes.indexOf(state.layoutMode);
      return { layoutMode: layoutModes[(currentIndex + 1) % layoutModes.length] };
    }),
}));
